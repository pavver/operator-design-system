//! Operator UI token generator.
//!
//! Reads `tokens/tokens.toml` and `tokens/icons/*.svg` and writes the platform sources:
//! - `web/operator-ui/style/tokens.css` (CSS custom properties for Leptos / any web stack)
//! - `crates/operator-ui-tokens/src/lib.rs` (Rust constants for Leptos and egui)
//! - `generated/kotlin/OperatorTokens.kt` (Kotlin constants for Jetpack Compose)
//!
//! Usage: `cargo run -p operator-tokens [-- --check]` from the repository root.
//! With `--check` the generator fails when any output is out of date instead of writing it.

use anyhow::{Context, Result, anyhow, bail};
use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use toml::{Table, Value};

const HEADER_NOTE: &str =
    "@generated by tools/operator-tokens from tokens/tokens.toml. Do not edit by hand.";

struct Color {
    r: u8,
    g: u8,
    b: u8,
    a: u8,
}

impl Color {
    fn parse(raw: &str) -> Result<Self> {
        let hex = raw
            .strip_prefix('#')
            .ok_or_else(|| anyhow!("color `{raw}` must start with #"))?;
        let byte = |i: usize| -> Result<u8> {
            let part = hex
                .get(i..i + 2)
                .ok_or_else(|| anyhow!("color `{raw}` is too short"))?;
            u8::from_str_radix(part, 16).with_context(|| format!("color `{raw}` is not valid hex"))
        };
        match hex.len() {
            6 => Ok(Self {
                r: byte(0)?,
                g: byte(2)?,
                b: byte(4)?,
                a: 255,
            }),
            8 => Ok(Self {
                r: byte(0)?,
                g: byte(2)?,
                b: byte(4)?,
                a: byte(6)?,
            }),
            _ => bail!("color `{raw}` must be #RRGGBB or #RRGGBBAA"),
        }
    }

    fn css(&self) -> String {
        if self.a == 255 {
            format!("#{:02X}{:02X}{:02X}", self.r, self.g, self.b)
        } else {
            format!("#{:02X}{:02X}{:02X}{:02X}", self.r, self.g, self.b, self.a)
        }
    }

    fn kotlin(&self) -> String {
        format!(
            "Color(0x{:02X}{:02X}{:02X}{:02X})",
            self.a, self.r, self.g, self.b
        )
    }

    fn rust(&self) -> String {
        format!("Rgba::new({}, {}, {}, {})", self.r, self.g, self.b, self.a)
    }
}

struct TypeStyle {
    name: String,
    size: f64,
    line: f64,
    weight: i64,
}

struct Palette {
    theme: String,
    mode: String,
    colors: Vec<(String, Color)>,
}

struct Icon {
    name: String,
    view_box: String,
    paths: Vec<String>,
}

struct Tokens {
    du_points: f64,
    tu_points: f64,
    font_family: String,
    font_fallback: Vec<String>,
    dimensions: Vec<(String, f64)>,
    typography: Vec<TypeStyle>,
    motion: Vec<(String, i64)>,
    palettes: Vec<Palette>,
    icons: Vec<Icon>,
}

fn table<'a>(parent: &'a Table, key: &str) -> Result<&'a Table> {
    parent
        .get(key)
        .and_then(Value::as_table)
        .ok_or_else(|| anyhow!("missing table `{key}`"))
}

fn number(value: &Value, ctx: &str) -> Result<f64> {
    match value {
        Value::Float(f) => Ok(*f),
        Value::Integer(i) => Ok(*i as f64),
        _ => bail!("`{ctx}` must be a number"),
    }
}

fn load(root: &Path) -> Result<Tokens> {
    let path = root.join("tokens/tokens.toml");
    let raw = fs::read_to_string(&path).with_context(|| format!("reading {}", path.display()))?;
    let doc: Table = raw
        .parse()
        .with_context(|| format!("parsing {}", path.display()))?;

    let units = table(&doc, "units")?;
    let du_points = number(
        units
            .get("du_points")
            .ok_or_else(|| anyhow!("units.du_points"))?,
        "units.du_points",
    )?;
    let tu_points = number(
        units
            .get("tu_points")
            .ok_or_else(|| anyhow!("units.tu_points"))?,
        "units.tu_points",
    )?;

    let font = table(&doc, "font")?;
    let font_family = font
        .get("family")
        .and_then(Value::as_str)
        .ok_or_else(|| anyhow!("font.family"))?
        .to_owned();
    let font_fallback = font
        .get("fallback")
        .and_then(Value::as_array)
        .ok_or_else(|| anyhow!("font.fallback"))?
        .iter()
        .map(|v| {
            v.as_str()
                .map(str::to_owned)
                .ok_or_else(|| anyhow!("font.fallback entries must be strings"))
        })
        .collect::<Result<Vec<_>>>()?;

    let dimensions = table(&doc, "dimensions")?
        .iter()
        .map(|(k, v)| Ok((k.clone(), number(v, &format!("dimensions.{k}"))?)))
        .collect::<Result<Vec<_>>>()?;

    let typography = table(&doc, "typography")?
        .iter()
        .map(|(name, v)| {
            let t = v
                .as_table()
                .ok_or_else(|| anyhow!("typography.{name} must be a table"))?;
            let get = |key: &str| -> Result<f64> {
                number(
                    t.get(key)
                        .ok_or_else(|| anyhow!("typography.{name}.{key}"))?,
                    key,
                )
            };
            Ok(TypeStyle {
                name: name.clone(),
                size: get("size")?,
                line: get("line")?,
                weight: get("weight")? as i64,
            })
        })
        .collect::<Result<Vec<_>>>()?;

    let motion = table(&doc, "motion")?
        .iter()
        .map(|(k, v)| {
            v.as_integer()
                .map(|ms| (k.clone(), ms))
                .ok_or_else(|| anyhow!("motion.{k} must be an integer"))
        })
        .collect::<Result<Vec<_>>>()?;

    let mut palettes = Vec::new();
    for (theme, modes) in table(&doc, "themes")? {
        let modes = modes
            .as_table()
            .ok_or_else(|| anyhow!("themes.{theme} must be a table"))?;
        for mode in ["dark", "light"] {
            let colors = table(modes, mode)
                .with_context(|| format!("themes.{theme}"))?
                .iter()
                .map(|(k, v)| {
                    let s = v
                        .as_str()
                        .ok_or_else(|| anyhow!("themes.{theme}.{mode}.{k} must be a string"))?;
                    Ok((
                        k.clone(),
                        Color::parse(s).with_context(|| format!("themes.{theme}.{mode}.{k}"))?,
                    ))
                })
                .collect::<Result<Vec<_>>>()?;
            palettes.push(Palette {
                theme: theme.clone(),
                mode: mode.to_owned(),
                colors,
            });
        }
    }
    let first = palettes
        .first()
        .ok_or_else(|| anyhow!("at least one theme is required"))?;
    let reference: Vec<&String> = first.colors.iter().map(|(k, _)| k).collect();
    for p in &palettes {
        let keys: Vec<&String> = p.colors.iter().map(|(k, _)| k).collect();
        if keys != reference {
            let a: BTreeSet<_> = reference.iter().collect();
            let b: BTreeSet<_> = keys.iter().collect();
            bail!(
                "palette {}.{} must define the same keys in the same order as {}.{} (missing: {:?}, extra: {:?})",
                p.theme,
                p.mode,
                first.theme,
                first.mode,
                a.difference(&b).collect::<Vec<_>>(),
                b.difference(&a).collect::<Vec<_>>()
            );
        }
    }

    Ok(Tokens {
        du_points,
        tu_points,
        font_family,
        font_fallback,
        dimensions,
        typography,
        motion,
        palettes,
        icons: load_icons(&root.join("tokens/icons"))?,
    })
}

fn attr<'a>(source: &'a str, name: &str) -> Vec<&'a str> {
    let needle = format!("{name}=\"");
    source
        .match_indices(needle.as_str())
        .filter_map(|(idx, _)| {
            let start = idx + needle.len();
            source[start..]
                .find('"')
                .map(|end| &source[start..start + end])
        })
        .collect()
}

fn load_icons(dir: &Path) -> Result<Vec<Icon>> {
    let mut entries = fs::read_dir(dir)
        .with_context(|| format!("reading {}", dir.display()))?
        .map(|e| e.map(|e| e.path()))
        .collect::<std::io::Result<Vec<PathBuf>>>()?;
    entries.retain(|p| p.extension().is_some_and(|e| e == "svg"));
    entries.sort();
    entries
        .iter()
        .map(|path| {
            let svg = fs::read_to_string(path)?;
            let name = path
                .file_stem()
                .and_then(|s| s.to_str())
                .ok_or_else(|| anyhow!("invalid icon file name {}", path.display()))?
                .to_owned();
            let view_box = attr(&svg, "viewBox")
                .first()
                .copied()
                .ok_or_else(|| anyhow!("{} has no viewBox", path.display()))?
                .to_owned();
            let paths: Vec<String> = attr(&svg, " d").into_iter().map(str::to_owned).collect();
            if paths.is_empty() {
                bail!("{} has no <path d=...>", path.display());
            }
            Ok(Icon {
                name,
                view_box,
                paths,
            })
        })
        .collect()
}

fn kebab(s: &str) -> String {
    s.replace('_', "-")
}

fn upper(s: &str) -> String {
    s.to_uppercase()
}

fn camel(s: &str) -> String {
    let mut out = String::new();
    let mut up = false;
    for c in s.chars() {
        if c == '_' {
            up = true;
        } else if up {
            out.extend(c.to_uppercase());
            up = false;
        } else {
            out.push(c);
        }
    }
    out
}

fn pascal(s: &str) -> String {
    let c = camel(s);
    let mut chars = c.chars();
    chars
        .next()
        .map(|f| f.to_uppercase().collect::<String>() + chars.as_str())
        .unwrap_or_default()
}

fn fmt_num(v: f64) -> String {
    let s = format!("{v}");
    if s.contains('.') { s } else { format!("{s}.0") }
}

fn font_stack(t: &Tokens) -> String {
    std::iter::once(format!("\"{}\"", t.font_family))
        .chain(t.font_fallback.iter().map(|f| {
            if f.contains(' ') {
                format!("\"{f}\"")
            } else {
                f.clone()
            }
        }))
        .collect::<Vec<_>>()
        .join(", ")
}

fn css(t: &Tokens) -> Result<String> {
    let mut o = String::new();
    writeln!(o, "/* {HEADER_NOTE} */\n")?;
    writeln!(o, ":root {{")?;
    writeln!(o, "  --op-du: {}px;", fmt_num(t.du_points))?;
    writeln!(o, "  --op-tu: {}rem;", t.tu_points / 16.0)?;
    writeln!(o, "  --op-font: {};", font_stack(t))?;
    for (name, v) in &t.dimensions {
        writeln!(o, "  --op-dim-{}: calc(var(--op-du) * {});", kebab(name), v)?;
    }
    for s in &t.typography {
        let n = kebab(&s.name);
        writeln!(o, "  --op-type-{n}-size: calc(var(--op-tu) * {});", s.size)?;
        writeln!(o, "  --op-type-{n}-line: calc(var(--op-tu) * {});", s.line)?;
        writeln!(o, "  --op-type-{n}-weight: {};", s.weight)?;
    }
    for (name, ms) in &t.motion {
        writeln!(o, "  --op-motion-{}: {ms}ms;", kebab(name))?;
    }
    writeln!(o, "}}")?;
    for p in &t.palettes {
        writeln!(
            o,
            "\n[data-op-theme=\"{}\"][data-op-mode=\"{}\"] {{",
            p.theme, p.mode
        )?;
        writeln!(o, "  color-scheme: {};", p.mode)?;
        for (name, c) in &p.colors {
            writeln!(o, "  --op-{}: {};", kebab(name), c.css())?;
        }
        writeln!(o, "}}")?;
    }
    Ok(o)
}

fn rust(t: &Tokens) -> Result<String> {
    let mut o = String::new();
    writeln!(
        o,
        "//! Operator UI design tokens shared by every Rust UI toolkit."
    )?;
    writeln!(o, "//!\n//! {HEADER_NOTE}\n")?;
    writeln!(o, "#![no_std]\n")?;
    o.push_str(
        "/// An sRGB color with straight alpha.\n\
         #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\n\
         pub struct Rgba {\n    pub r: u8,\n    pub g: u8,\n    pub b: u8,\n    pub a: u8,\n}\n\n\
         impl Rgba {\n    pub const fn new(r: u8, g: u8, b: u8, a: u8) -> Self {\n        Self { r, g, b, a }\n    }\n}\n\n\
         /// A text style expressed in Type Units (TU).\n\
         #[derive(Clone, Copy, Debug, PartialEq)]\n\
         pub struct TypeStyle {\n    pub size: f32,\n    pub line: f32,\n    pub weight: u16,\n}\n\n\
         /// A vector icon: SVG viewBox plus path data.\n\
         #[derive(Clone, Copy, Debug, PartialEq, Eq)]\n\
         pub struct Icon {\n    pub name: &'static str,\n    pub view_box: &'static str,\n    pub paths: &'static [&'static str],\n}\n\n",
    );
    writeln!(
        o,
        "/// Logical points per Design Unit.\npub const DU_POINTS: f32 = {};",
        fmt_num(t.du_points)
    )?;
    writeln!(
        o,
        "/// Scalable logical points per Type Unit.\npub const TU_POINTS: f32 = {};",
        fmt_num(t.tu_points)
    )?;
    writeln!(
        o,
        "/// Primary font family.\npub const FONT_FAMILY: &str = {:?};\n",
        t.font_family
    )?;

    writeln!(
        o,
        "/// Spatial tokens in Design Units (DU).\npub mod dim {{"
    )?;
    for (name, v) in &t.dimensions {
        writeln!(o, "    pub const {}: f32 = {};", upper(name), fmt_num(*v))?;
    }
    writeln!(o, "}}\n")?;

    writeln!(
        o,
        "/// Text styles in Type Units (TU).\npub mod typography {{\n    use super::TypeStyle;"
    )?;
    for s in &t.typography {
        writeln!(
            o,
            "    pub const {}: TypeStyle = TypeStyle {{ size: {}, line: {}, weight: {} }};",
            upper(&s.name),
            fmt_num(s.size),
            fmt_num(s.line),
            s.weight
        )?;
    }
    writeln!(o, "}}\n")?;

    writeln!(
        o,
        "/// Motion durations in milliseconds.\npub mod motion {{"
    )?;
    for (name, ms) in &t.motion {
        writeln!(o, "    pub const {}_MS: u32 = {ms};", upper(name))?;
    }
    writeln!(o, "}}\n")?;

    let first = t.palettes.first().ok_or_else(|| anyhow!("no palettes"))?;
    writeln!(
        o,
        "/// A complete semantic color palette for one theme and mode.\n#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub struct Palette {{"
    )?;
    for (name, _) in &first.colors {
        writeln!(o, "    pub {name}: Rgba,")?;
    }
    writeln!(o, "}}\n")?;

    let themes: Vec<&String> = {
        let mut seen = Vec::new();
        for p in &t.palettes {
            if !seen.contains(&&p.theme) {
                seen.push(&p.theme);
            }
        }
        seen
    };
    writeln!(
        o,
        "/// Available themes.\n#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\npub enum Theme {{"
    )?;
    for th in &themes {
        writeln!(o, "    {},", pascal(th))?;
    }
    writeln!(
        o,
        "}}\n\nimpl Theme {{\n    pub const ALL: &'static [Theme] = &[{}];\n",
        themes
            .iter()
            .map(|th| format!("Theme::{}", pascal(th)))
            .collect::<Vec<_>>()
            .join(", ")
    )?;
    writeln!(
        o,
        "    /// Stable identifier used by `data-op-theme` and settings storage.\n    pub const fn id(self) -> &'static str {{\n        match self {{"
    )?;
    for th in &themes {
        writeln!(o, "            Theme::{} => {:?},", pascal(th), th)?;
    }
    writeln!(
        o,
        "        }}\n    }}\n\n    pub const fn palette(self, dark: bool) -> &'static Palette {{\n        match (self, dark) {{"
    )?;
    for th in &themes {
        writeln!(
            o,
            "            (Theme::{0}, true) => &palettes::{1}_DARK,\n            (Theme::{0}, false) => &palettes::{1}_LIGHT,",
            pascal(th),
            upper(th)
        )?;
    }
    writeln!(o, "        }}\n    }}\n}}\n")?;

    writeln!(
        o,
        "/// Palettes per theme and mode.\npub mod palettes {{\n    use super::{{Palette, Rgba}};"
    )?;
    for p in &t.palettes {
        writeln!(
            o,
            "\n    pub const {}_{}: Palette = Palette {{",
            upper(&p.theme),
            upper(&p.mode)
        )?;
        for (name, c) in &p.colors {
            writeln!(o, "        {name}: {},", c.rust())?;
        }
        writeln!(o, "    }};")?;
    }
    writeln!(o, "}}\n")?;

    writeln!(
        o,
        "/// Vector icons imported from tokens/icons.\npub mod icons {{\n    use super::Icon;"
    )?;
    for i in &t.icons {
        let paths = i
            .paths
            .iter()
            .map(|p| format!("{p:?}"))
            .collect::<Vec<_>>()
            .join(", ");
        writeln!(
            o,
            "    pub const {}: Icon = Icon {{ name: {:?}, view_box: {:?}, paths: &[{paths}] }};",
            upper(&i.name),
            i.name,
            i.view_box
        )?;
    }
    writeln!(
        o,
        "\n    pub const ALL: &[Icon] = &[{}];",
        t.icons
            .iter()
            .map(|i| upper(&i.name))
            .collect::<Vec<_>>()
            .join(", ")
    )?;
    writeln!(o, "}}")?;
    Ok(o)
}

fn kotlin(t: &Tokens) -> Result<String> {
    let mut o = String::new();
    writeln!(
        o,
        "// {HEADER_NOTE}\npackage io.github.pavver.operatorui.tokens\n"
    )?;
    writeln!(o, "import androidx.compose.ui.graphics.Color")?;
    writeln!(o, "import androidx.compose.ui.text.font.FontWeight")?;
    writeln!(o, "import androidx.compose.ui.unit.Dp")?;
    writeln!(o, "import androidx.compose.ui.unit.TextUnit")?;
    writeln!(o, "import androidx.compose.ui.unit.dp")?;
    writeln!(o, "import androidx.compose.ui.unit.sp\n")?;
    writeln!(
        o,
        "/** Spatial tokens; values are Design Units converted to Dp. */\nobject OperatorDu {{"
    )?;
    for (name, v) in &t.dimensions {
        writeln!(
            o,
            "    val {}: Dp = {}.dp",
            pascal(name),
            fmt_num(v * t.du_points)
        )?;
    }
    writeln!(o, "}}\n")?;
    writeln!(
        o,
        "data class OperatorTypeToken(val size: TextUnit, val line: TextUnit, val weight: FontWeight)\n"
    )?;
    writeln!(
        o,
        "/** Text styles; values are Type Units converted to sp. */\nobject OperatorType {{"
    )?;
    for s in &t.typography {
        writeln!(
            o,
            "    val {} = OperatorTypeToken({}.sp, {}.sp, FontWeight({}))",
            pascal(&s.name),
            fmt_num(s.size * t.tu_points),
            fmt_num(s.line * t.tu_points),
            s.weight
        )?;
    }
    writeln!(o, "}}\n")?;
    writeln!(
        o,
        "/** Motion durations in milliseconds. */\nobject OperatorMotion {{"
    )?;
    for (name, ms) in &t.motion {
        writeln!(o, "    const val {}: Int = {ms}", pascal(name))?;
    }
    writeln!(o, "}}\n")?;
    let first = t.palettes.first().ok_or_else(|| anyhow!("no palettes"))?;
    writeln!(o, "data class OperatorPalette(")?;
    let fields: Vec<String> = first
        .colors
        .iter()
        .map(|(n, _)| format!("    val {}: Color", camel(n)))
        .collect();
    writeln!(o, "{}\n)\n", fields.join(",\n"))?;
    writeln!(o, "object OperatorPalettes {{")?;
    for p in &t.palettes {
        writeln!(
            o,
            "    val {}{} = OperatorPalette(",
            pascal(&p.theme),
            pascal(&p.mode)
        )?;
        let vals: Vec<String> = p
            .colors
            .iter()
            .map(|(n, c)| format!("        {} = {}", camel(n), c.kotlin()))
            .collect();
        writeln!(o, "{}\n    )", vals.join(",\n"))?;
    }
    writeln!(o, "}}")?;
    Ok(o)
}

/// Formats generated Rust with rustfmt so `cargo fmt` keeps the file stable.
fn rustfmt(source: &str) -> Result<String> {
    use std::io::Write;
    use std::process::{Command, Stdio};
    let mut child = Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()
        .context("running rustfmt")?;
    child
        .stdin
        .take()
        .ok_or_else(|| anyhow!("rustfmt stdin unavailable"))?
        .write_all(source.as_bytes())?;
    let output = child.wait_with_output()?;
    if !output.status.success() {
        bail!(
            "rustfmt failed: {}",
            String::from_utf8_lossy(&output.stderr)
        );
    }
    String::from_utf8(output.stdout).context("rustfmt output is not UTF-8")
}

fn main() -> Result<()> {
    let check = std::env::args().any(|a| a == "--check");
    let root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .ancestors()
        .nth(2)
        .ok_or_else(|| anyhow!("cannot resolve repository root"))?
        .to_path_buf();
    let tokens = load(&root)?;

    let outputs = [
        (root.join("web/operator-ui/style/tokens.css"), css(&tokens)?),
        (
            root.join("crates/operator-ui-tokens/src/lib.rs"),
            rustfmt(&rust(&tokens)?)?,
        ),
        (
            root.join("generated/kotlin/OperatorTokens.kt"),
            kotlin(&tokens)?,
        ),
    ];

    let mut stale = Vec::new();
    for (path, content) in &outputs {
        let current = fs::read_to_string(path).unwrap_or_default();
        if current == *content {
            continue;
        }
        if check {
            stale.push(path.display().to_string());
        } else {
            if let Some(parent) = path.parent() {
                fs::create_dir_all(parent)?;
            }
            fs::write(path, content).with_context(|| format!("writing {}", path.display()))?;
            println!("wrote {}", path.display());
        }
    }
    if !stale.is_empty() {
        bail!("generated files are out of date: {}", stale.join(", "));
    }
    println!(
        "tokens: {} dimensions, {} text styles, {} motion values, {} palettes, {} icons",
        tokens.dimensions.len(),
        tokens.typography.len(),
        tokens.motion.len(),
        tokens.palettes.len(),
        tokens.icons.len()
    );
    Ok(())
}
